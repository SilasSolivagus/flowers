-- 推翻 0029 的 `tree_entry`：**我优化错了那一半**。
--
-- ## 错在哪
--
-- 0029 把索引拆成「内容层（blob_index）+ 提交层（tree_entry）」。内容层是对的：
-- 同一份内容只解析一次，两个仓的 HEAD 合计 277 行，而那正是「做一次」的性质。
-- 提交层是错的，而且错得可以由实测直接读出来：
--
--   * 一个提交就是**一整棵树**：638 行（123pan-uni-app）、575 行（123pan-pc）；
--   * 4 个提交 = 2422 行；行数按 `文件 × 提交` 增长；
--   * 139 个仓 × 几千个提交 = **几百万行**，存的是 git 用 0.3 秒就能重新吐出来的东西。
--
-- 一句话：**解析文件内容是贵的（值得缓存），列一棵树是便宜的（不值得缓存）**。
-- 所以这一层整个删掉，装配时**现读** `git ls-tree -r <sha>`（它本来就返回 path + blob id，
-- 与 `blob_index.blob_sha` 正好能 join）。
--
-- ## 删它为什么是安全的
--
-- 没有任何东西读它：`assembleIndex()` 改成现读树（见 `core/codemirror/index-store.ts`），
-- 库里其他表与它没有外键，`reset.ts` 的清单里也从来没有它（它是「故意留下」的那一侧）。
-- 唯一写过它的是 0029 之后的 `writeTreeRows()`，那个函数随本迁移一起删掉。
--
-- ## 顺带删掉 `code_index`
--
-- 0029 把它留成「历史对照」（演示库那 32 行是上一版的实测数据）。这一轮 reshape 的
-- 对照已经做完并写进报告（`docs/superpowers/plans/2026-11-08-blob-index.md`
-- §4 的「索引内容与旧路径逐字相同」），而新的装配路径与它没有交集：
-- `repoIndex()` / `readIndex()` 一个字节都不读它。留着一张没人读、没人写的快照表只会
-- 让下一个人以为它是缓存。重建那份对照的成本是重扫一次镜像，而它已经完成了使命。
drop table if exists tree_entry;
drop table if exists code_index;
