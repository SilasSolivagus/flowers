-- Ruling 2（2026-11-08）：没有负责人的需求一律回到「收集」。
--
-- 口径（owner）：一条没有负责人的需求在流程里**没有主人**，任何「待设计 / 待评审 /
-- 待排期 / 开发中」都只是别人替它写下的一个状态，没有人欠它一个动作。所以把它们统统
-- 退回收集列：那正是「没人接手的活排队等人认领」的地方（看板的收集列上每张无主卡都带着
-- 「认领」按钮，见 `app/components/ClaimButton.tsx`）。
--
-- ## 为什么 `state_entered_at` 也重置（刻意，不是顺手）
--
-- 这一列的含义是「**进入当前状态的时刻**」，看板卡片上那行「停了 N 天」、抽屉里的
-- 「进入本状态」、以及所有按停留时间做的排序都读它。这些行现在真的重新进入了收集状态，
-- 它们从这一刻起**重新开始排队等领取**（而不是「在待设计停了 40 天」——那 40 天里
-- 根本没有人负责它，把它算作停留时间会让看板把一批无主需求显示成「卡了很久」，
-- 而它们卡住的原因与时长无关：是没人认领）。
--
-- 反过来说：有负责人的行**一个字都不动**（下面的 where 同时限定
-- `owner_member_id is null` 与 `state <> 'inbox'`，两条件都成立才更新）。
--
-- ## 幂等
--
-- `state <> 'inbox'` 让第二次跑命中 0 行。**不能**只靠这一点：第一次跑完所有无主行都在
-- inbox，第二次跑确实什么都不改；但若之后又有人把某条无主需求推去别处（界面拦得住，
-- MCP / 脚本不一定），再跑一次就会把它拉回来——这正是这条迁移想表达的口径，所以重复
-- 执行是安全的、而且是**期望**的。
--
-- 实测（执行前）：815 行里 195 行无负责人，其中 143 行已在收集，**52 行会被这条语句移动**
--   design 22 · rejected 17 · shelved 6 · live 6 · dev 1
-- 执行后 `select state, count(*) from requirements where owner_member_id is null group by state`
-- 只剩 `inbox | 195` 一行。
update requirements
   set state = 'inbox',
       state_entered_at = now()
 where owner_member_id is null
   and state <> 'inbox';
