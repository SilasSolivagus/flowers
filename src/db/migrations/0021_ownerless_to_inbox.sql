-- Ruling 2（2026-11-08，同日修订）：没有负责人的需求回到「收集」——**但终态不动**。
--
-- 口径（owner）：一条没有负责人的需求在流程里**没有主人**，任何「待设计 / 待评审 /
-- 待排期 / 开发中」都只是别人替它写下的一个状态，没有人欠它一个动作。所以把它们退回
-- 收集列：那正是「没人接手的活排队等人认领」的地方（看板的收集列上每张无主卡都带着
-- 「认领」按钮，见 `app/components/ClaimButton.tsx`）。
--
-- ## 修订：`rejected` / `shelved` / `live` 三类**不动**
--
-- 第一版把「没有负责人」当成了唯一的判断依据，于是 `rejected` / `shelved` / `live`
-- 也被拉回收集——这是错的。owner 的原话：
--
--   没有负责人的需求回收集，**但下列状态不动**：`shelved`（搁置）、`live`（已上线）、
--   `rejected`（已拒绝）。**终态是结论，不是流程位置。** 没有负责人只说明「当年谁负责
--   没记录」，不说明「这件事要重来」。
--
-- 两个具体的后果，都不是风格问题：
--
-- - `rejected` 拉回收集，它就重新变成一张可以立项的卡——**等于悄悄撤销一次拒绝决定**。
--   拒绝是有人做过的一个判断（有理由、有当时的信息），把它还原成「未处理」是抹掉它。
-- - `live` 拉回收集，一个**已经在跑**的功能在看板上显示「等领取」——谁看到都会去认领，
--   然后发现自己「接手」了一个上线三个月的功能。
--
-- 所以判据从「无主」变成「无主 **且** 当前不是终态」：终态里没有「谁欠它一个动作」这件事，
-- 把终态留在原地不会让任何活卡住；而 `design` / `ready` / `dev` / `test` 这些**进行中**
-- 的位置，无主就意味着真的没人推进，才是收回收集的对象。
--
-- ## 为什么 `state_entered_at` 也重置（刻意，不是顺手）
--
-- 这一列的含义是「**进入当前状态的时刻**」，看板卡片上那行「停了 N 天」、抽屉里的
-- 「进入本状态」、以及所有按停留时间做的排序都读它。这些行现在真的重新进入了收集状态，
-- 它们从这一刻起**重新开始排队等领取**（而不是「在待设计停了 40 天」——那 40 天里
-- 根本没有人负责它，把它算作停留时间会让看板把一批无主需求显示成「卡了很久」，
-- 而它们卡住的原因与时长无关：是没人认领）。
--
-- 终态那三类**尤其**不能借用这个 now()：`live` 的真实进入时刻是它上线那天，`rejected`
-- 是被拒那天。给它们盖上「今天」等于说「它今天才上线 / 才被拒」——所以它们干脆不进
-- 这条语句，而不是「进来了再改回去」。
--
-- ## 幂等
--
-- `state not in ('inbox', ...)` 让第二次跑命中 0 行。**不能**只靠这一点：第一次跑完所有
-- 该动的无主行都在 inbox，第二次跑确实什么都不改；但若之后又有人把某条无主需求推去别处
-- （界面拦得住，MCP / 脚本不一定），再跑一次就会把它拉回来——这正是这条迁移想表达的
-- 口径，所以重复执行是安全的、而且是**期望**的。
--
-- ## 这条迁移被**就地改过**（刻意）
