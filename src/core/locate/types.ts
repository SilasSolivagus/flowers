/**
 * 「定位」这一步的数据形状：一次查找可能给出的三种结果，以及一条候选长什么样。
 *
 * 为什么值得单独一个文件：Task 5/6 负责产出它、Task 7 负责记下来、Task 8/9 负责渲染
 * 进材料。如果三处各写各的字面量（`'not_found'` / `'none'` / `'empty'`），早晚会有人
 * 把「没读到」和「没找到」拼成同一个值——那正是这个仓库修过两轮的病（见
 * `core/codemirror/mirror.ts` 的 `mergeHistory`：失败被当成空结果）。名字只在这里定义
 * 一次，下游一律 import，不猜。
 */

/**
 * 我们对一条线索有多确定。
 *
 * 第一版只会有 `low`：检索还没到能被信任的程度。留着 `high` 不是为空而留，而是让
 * 「以后能升到 high」这件事在类型里有个位置——真升的时候改的是取值，不是三处签名。
 *
 * 两个值的含义固定下来，别在其他地方重新解释：
 * - `low`＝「可能是这里」，等于给研发的一条线索；
 * - `high`＝「就是这里」，第一版不产出。
 */
export type Confidence = 'high' | 'low';

/**
 * 线索是从哪一路找来的。三路必须可区分：同一条路径从「历史」命中和从「grep」命中，
 * 可信度与要写的理由完全不同；混成一个来源，材料里就说不清「凭什么认为是这里」。
 *
 * - `history`：某次合并的信息或文件列表对上了；
 * - `structure`：目录、文件、路由的命名对上了；
 * - `grep`：代码文本里搜到了需求里的关键词。
 */
export type Source = 'history' | 'structure' | 'grep';

/**
 * 一条候选：路径 + 给 PM 看的理由 + 来源 + 排序分。
 *
 * `reason` 是**给人读的整句**（「出自 11-03 那次合并」），不是枚举键——材料里直接
 * 渲染它，PM 不会去查一个 code 再翻译一遍。这也意味着它必须自带上下文，不能只写
 * 「历史命中」。
 *
 * `score` 只用来排序，不对外展示：分数的绝对值没有意义，跨版本比较更是错的（换一版
 * 检索，同一处代码的分数就变了）。
 */
export type Candidate = {
  path: string;
  reason: string;
  source: Source;
  score: number;
};

/**
 * 一次定位的三种结果，**不可合并成两种**。
 *
 * - `absent`：我们**没看到**代码（镜像连不上、仓没配）。这不是「没有」，是「不知道」；
 * - `none`：看到了，**没有**相似的实现。这才是一个结论；
 * - `candidates`：找到了候选，第一版一律 `low`。
 *
 * 为什么用三支联合而不是 `{ items: Candidate[]; why?: string }`：后者能表达「空且
 * 带原因」这种自相矛盾的状态，调用方每次都得记得先看 `why` 再看长度，忘了就是又
 * 一次「失败被当成空结果」。联合类型逼着「到底属于哪一种」在编译期就被选出来，
 * 文案层也就没有第三种说法可写（措辞见 `copy.ts`）。
 */
export type LocateResult =
  | { kind: 'absent'; why: string }
  | { kind: 'none' }
  | { kind: 'candidates'; confidence: Confidence; items: Candidate[] };
