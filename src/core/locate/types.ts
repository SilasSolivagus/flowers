/**
 * 「定位」这一步的数据形状：一次查找可能给出的三种结果，以及一条候选长什么样。
 *
 * 为什么值得单独一个文件：Task 5/6 负责产出它、Task 7 负责记下来、Task 8/9 负责渲染
 * 进材料。如果三处各写各的字面量（`'not_found'` / `'none'` / `'empty'`），早晚会有人
 * 把「没读到」和「没找到」拼成同一个值——那正是这个仓库修过两轮的病（见
 * `core/codemirror/mirror.ts` 的 `mergeHistory`：失败被当成空结果）。名字只在这里定义
 * 一次，下游一律 import，不猜。
 */

/**
 * 我们对一条线索有多确定。
 *
 * 第一版只会有 `low`：检索还没到能被信任的程度。留着 `high` 不是为空而留，而是让
 * 「以后能升到 high」这件事在类型里有个位置——真升的时候改的是取值，不是三处签名。
 *
 * 两个值的含义固定下来，别在其他地方重新解释：
 * - `low`＝「可能是这里」，等于给研发的一条线索；
 * - `high`＝「就是这里」，第一版不产出。
 */
export type Confidence = 'high' | 'low';

/**
 * 线索是从哪一路找来的。两路必须可区分：同一条路径从「历史」命中和从「结构命名」命中，
 * 可信度与要写的理由完全不同；混成一个来源，材料里就说不清「凭什么认为是这里」。
 *
 * - `history`：某次合并的信息或文件列表对上了（走查，`history.ts`）；
 * - `structure`：目录、文件、路由的命名对上了（评审，`structure.ts`）。
 *
 * **没有 `grep`。** 这个值原本在这里，但两条路都不产出它：走查只走合并历史，评审只走
 * 结构索引（`structure.ts` 明确跳过 `locateAcross` 的 `source: 'grep'` 分支——那是
 * 「这个仓没有索引，退回去文本搜吧」的说明文字，不是候选）。留着一个永远不出现的取值，
 * 读者就会以为存在第三条路径，甚至在渲染层为它写一句文案——那正是本次改造要消灭的
 * 那种「看起来有、其实没有」。真需要文本检索时，先有那条路再把这个值加回来。
 */
export type Source = 'history' | 'structure';

/**
 * 一条候选：路径 + 给 PM 看的理由 + 来源 + 排序分。
 *
 * `reason` 是**给人读的整句**（「出自 11-03 那次合并」），不是枚举键——材料里直接
 * 渲染它，PM 不会去查一个 code 再翻译一遍。这也意味着它必须自带上下文，不能只写
 * 「历史命中」。
 *
 * `score` 只用来排序，不对外展示：分数的绝对值没有意义，跨版本比较更是错的（换一版
 * 检索，同一处代码的分数就变了）。
 */
export type Candidate = {
  path: string;
  reason: string;
  source: Source;
  score: number;
};

/**
 * 一次定位的三种结果，**不可合并成两种**。
 *
 * - `absent`：这一轮我们**没看到**东西。它不是「没有」，是「不知道」；
 * - `none`：看到了，**没有**相似的实现。这才是一个结论；
 * - `candidates`：找到了候选，第一版一律 `low`。
 *
 * `absent` 有两个来源，**类型相同、措辞不同**（两句话都在 `copy.ts`，由
 * `renderLocate` 的第二个参数选）：
 *
 * 1. **代码本身没读到**（镜像连不上、仓没配、HEAD/树读不出来）→ `ABSENT_LINE`，
 *    第一句是「代码没读到」；
 * 2. **代码读到了，合并历史/库没读到**（`commit_history` 补齐或读库失败）→
 *    `ABSENT_HISTORY_LINE`，第一句是「代码读到了，但合并历史没读到」。
 *
 * 为什么要分成两句、却仍然合成一个类型：缺口的位置决定**该叫谁去修**（镜像/仓配置
 * 归运维，历史库归库侧），而「这一轮没有现状判断」这件事两者相同——所以取值不动，
 * 只在渲染层分流。2026-11-07 终审就是在这里发现「代码读到了、历史没读到」被说成了
 * 「代码没读到」，PM 因此被指向去催镜像。具体是哪一半，由**调用点**知道（它刚调用
 * 的是哪个读口），`why` 只负责带原始原因（那才是 PM 能转述的线索）。
 *
 * 为什么不把两种来源做成两个 `kind`：那会让「三种结果」变成四种，而下游（记账、
 * 材料、统计）每一处都要多一个分支，其中任一处漏写就会把一种缺口算成另一种——
 * 这正是本仓修过两轮的病（见 `core/codemirror/mirror.ts` 的 `mergeHistory`：
 * 失败被当成空结果）。
 *
 * 为什么用三支联合而不是 `{ items: Candidate[]; why?: string }`：后者能表达「空且
 * 带原因」这种自相矛盾的状态，调用方每次都得记得先看 `why` 再看长度，忘了就是又
 * 一次「失败被当成空结果」。联合类型逼着「到底属于哪一种」在编译期就被选出来，
 * 文案层也就没有第三种说法可写（措辞见 `copy.ts`）。
 */
export type LocateResult =
  | { kind: 'absent'; why: string }
  | { kind: 'none' }
  | { kind: 'candidates'; confidence: Confidence; items: Candidate[] };
